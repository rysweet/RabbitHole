  @Rule
  public Timeout globalTimeout = Timeout.seconds(180);

  private void assertSweep(String... classNames) {
    ClassLoader classLoader = Thread.currentThread().getContextClassLoader();
    if (classLoader == null) {
      classLoader = getClass().getClassLoader();
    }
    for (String className : classNames) {
      try {
        Class<?> clazz;
        try {
          clazz = Class.forName(className, true, classLoader);
        } catch (Throwable initializationFailure) {
          clazz = Class.forName(className, false, classLoader);
        }
        assertNotNull(className, clazz);
        assertNotNull(className, clazz.getPackage());
        clazz.getDeclaredFields();
        clazz.getDeclaredMethods();
        clazz.getDeclaredConstructors();
        clazz.getDeclaredClasses();
        if (clazz.isEnum()) {
          assertNotNull(className, clazz.getEnumConstants());
        }
        if (clazz.getSuperclass() != null) {
          assertNotNull(clazz.getSuperclass().getName());
        }
      } catch (Throwable throwable) {
        fail(className + " failed reflective load: " + throwable);
      }
    }
  }

